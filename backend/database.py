"""Database adapter: isolated PostgreSQL schema, SQLite for local tests/demos."""
import os,re,sqlite3,hashlib,atexit,threading
from pathlib import Path
from contextlib import contextmanager
from urllib.parse import urlsplit,urlunsplit,parse_qsl,urlencode
from dotenv import load_dotenv
load_dotenv(Path(__file__).with_name('.env'))
load_dotenv(Path(__file__).parent.parent/'.env')
DATABASE_URL=os.getenv('DATABASE_URL') or os.getenv('POSTGRES_URL') or os.getenv('POSTGRES_URL_NON_POOLING') or ''
BACKEND=os.getenv('VERA_DB_BACKEND') or ('postgres' if DATABASE_URL else 'sqlite')
SCHEMA=os.getenv('VERA_DB_SCHEMA','vera')
if SCHEMA in ('public','information_schema') or SCHEMA.startswith('pg_') or not re.fullmatch(r'[a-z][a-z0-9_]{0,62}',SCHEMA):raise RuntimeError('Invalid VERA_DB_SCHEMA')
if BACKEND not in ('sqlite','postgres'):raise RuntimeError('VERA_DB_BACKEND must be sqlite or postgres')
if os.getenv('VERCEL') and BACKEND!='postgres':raise RuntimeError('Vercel requires a persistent PostgreSQL connection')
AUTO_IDS={'customers','contacts','inquiries','followups','quotes','quote_versions','quote_lines','orders','status_history'}
LOCK_ID=int.from_bytes(hashlib.sha256(('vera:'+SCHEMA).encode()).digest()[:8],'big',signed=True)

class Row(dict):
    def __getitem__(self,key):return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)

class Result:
    def __init__(self,cursor,insert_id=None):self.cursor=cursor;self.lastrowid=insert_id
    def fetchone(self):
        r=self.cursor.fetchone();return Row(r) if r is not None else None
    def fetchall(self):return [Row(r) for r in self.cursor.fetchall()]
    def __iter__(self):
        for r in self.cursor:yield Row(r)

class Postgres:
    def __init__(self,connection):self.connection=connection
    def ensure_schema(self):
        from psycopg import sql
        self.connection.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(SCHEMA)))
    def executescript(self,script):
        for statement in script.split(';'):
            if statement.strip():
                statement=statement.replace('id INTEGER PRIMARY KEY','id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace('INTEGER REFERENCES','BIGINT REFERENCES').replace('INTEGER UNIQUE REFERENCES','BIGINT UNIQUE REFERENCES').replace('entity_id INTEGER','entity_id BIGINT').replace('expires_at REAL','expires_at DOUBLE PRECISION')
                self.connection.execute(statement)
    def execute(self,query,params=()):
        pragma=re.fullmatch(r'PRAGMA table_info\((\w+)\)',query.strip(),re.I)
        if pragma:
            return Result(self.connection.execute('SELECT column_name AS name FROM information_schema.columns WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position',(SCHEMA,pragma.group(1))))
        if query.strip().upper()=='BEGIN IMMEDIATE':
            return Result(self.connection.execute('SELECT pg_advisory_xact_lock(%s)',(LOCK_ID,)))
        query=query.replace('?','%s')
        ignore=bool(re.match(r'INSERT OR IGNORE',query,re.I))
        if ignore:query=re.sub(r'INSERT OR IGNORE','INSERT',query,count=1,flags=re.I)+' ON CONFLICT DO NOTHING'
        insert=re.match(r'INSERT INTO (\w+)',query,re.I)
        returning=bool(insert and insert.group(1).lower() in AUTO_IDS)
        if returning:query+=' RETURNING id'
        cursor=self.connection.execute(query,params)
        insert_id=cursor.fetchone()['id'] if returning else None
        return Result(cursor,insert_id)

_pool=None
_pool_lock=threading.Lock()
def close_pool():
    global _pool
    if _pool is not None:
        _pool.close(timeout=3);_pool=None
atexit.register(close_pool)

def connection_url():
    if not DATABASE_URL:raise RuntimeError('Set DATABASE_URL for PostgreSQL')
    parts=urlsplit(DATABASE_URL.strip())
    if parts.scheme not in ('postgres','postgresql') or not parts.hostname:raise RuntimeError('Invalid PostgreSQL connection configuration')
    supported={'sslmode','connect_timeout','application_name','channel_binding','options'}
    url=urlunsplit((parts.scheme,parts.netloc,parts.path,urlencode([(k,v) for k,v in parse_qsl(parts.query) if k in supported]),''))
    from psycopg.conninfo import conninfo_to_dict
    try:conninfo_to_dict(url)
    except Exception:raise RuntimeError('Invalid PostgreSQL connection configuration') from None
    return url

@contextmanager
def connect(sqlite_path):
    if BACKEND=='sqlite':
        con=sqlite3.connect(sqlite_path,timeout=20);con.row_factory=sqlite3.Row;con.execute('PRAGMA foreign_keys=ON')
        try:
            with con:yield con
        finally:con.close()
        return
    from psycopg import sql
    from psycopg.rows import dict_row
    from psycopg_pool import ConnectionPool,PoolTimeout
    global _pool
    with _pool_lock:
        if _pool is None:
            _pool=ConnectionPool(connection_url(),min_size=0,max_size=6,timeout=20,max_idle=60,max_lifetime=600,check=ConnectionPool.check_connection,kwargs={'connect_timeout':15,'prepare_threshold':None,'row_factory':dict_row},name='vera',open=True)
    try:
        with _pool.connection() as con:
            con.execute(sql.SQL('SET LOCAL search_path TO {}, pg_temp').format(sql.Identifier(SCHEMA)))
            yield Postgres(con)
    except PoolTimeout:raise RuntimeError('PostgreSQL connection timed out; check server configuration and network') from None
